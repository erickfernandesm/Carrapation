/** Quantidade total de icones do catalogo, usada no rodape do seletor. */
export const TOTAL_ICONES = CATEGORIAS_ICONES.reduce((soma, c) => soma + c.icones.length, 0)

/**
 * Filtra o catalogo pelo que foi digitado.
 * Devolve apenas as categorias que sobraram com pelo menos um icone.
 */
export function buscarIcones(termo: string): CategoriaIcones[] {
  const alvo = termo.trim().toLowerCase()
  if (!alvo) return CATEGORIAS_ICONES

  const palavras = alvo.split(/\s+/)

  return CATEGORIAS_ICONES.map((categoria) => ({
    ...categoria,
    icones: categoria.icones.filter(([emoji, termos]) => {
      if (emoji === alvo) return true
      const texto = `${termos} ${categoria.nome.toLowerCase()}`
      return palavras.every((palavra) => texto.includes(palavra))
    }),
  })).filter((categoria) => categoria.icones.length > 0)
}
